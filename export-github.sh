#!/usr/bin/env bash
# export-github.sh
#
# Exports the live GitHub configuration for timgladwell/violet into
# docs/current-state/github-export/ so it is committed to the repo.
#
# WHY THIS EXISTS
#   GitHub holds configuration that is not reproducible from this repo: the
#   branch rulesets that make release promotion safe (ADR 0001), merge settings,
#   Actions permissions, labels. They are changed in the Settings UI with no PR
#   behind them, so drift is silent. This export is the record to rebuild from,
#   and `git status` after a run IS the drift check. The reasoning is in
#   docs/current-state/github-config.md.
#
# WHAT IT DOES NOT CAPTURE
#   Secret values (only Actions secret and variable *names*), and the Cloudflare
#   Pages GitHub App installation, which a user token cannot read - see
#   github-config.md for how to check that by hand.
#
# USAGE
#   ./export-github.sh      # uses your existing `gh auth login` session
#   Read-only: every call is a GET. Reading rulesets and Actions permissions
#   needs admin on the repo, which the owner's session has.

set -uo pipefail

REPO="${GH_REPO_SLUG:-timgladwell/violet}"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="$REPO_ROOT/docs/current-state/github-export"

command -v gh >/dev/null || { echo "ERROR: gh is required (brew install gh)" >&2; exit 1; }
command -v jq >/dev/null || { echo "ERROR: jq is required (brew install jq)" >&2; exit 1; }
gh auth status >/dev/null 2>&1 || { echo "ERROR: not logged in - run: gh auth login" >&2; exit 1; }

mkdir -p "$OUT"
FAILED=0

get() { # get <api-path> <outfile> <jq-filter>
  # Volatile fields (timestamps, counters, URLs) are filtered out so a rerun
  # with no configuration change produces no diff.
  if gh api --paginate "repos/$REPO${1:+/$1}" | jq -s "$3" > "$OUT/$2.tmp"; then
    mv "$OUT/$2.tmp" "$OUT/$2"
    echo "  ok    $2"
  else
    rm -f "$OUT/$2.tmp"
    echo "  FAIL  $2 ($1)" >&2
    FAILED=1
  fi
}

echo "== $REPO"
get "" repo.json '.[0] | {visibility, default_branch, has_issues, has_projects, has_wiki, has_discussions,
  allow_merge_commit, allow_squash_merge, allow_rebase_merge, allow_auto_merge, allow_update_branch,
  delete_branch_on_merge, merge_commit_title, merge_commit_message, web_commit_signoff_required,
  security_and_analysis}'
# The list endpoint omits rules; fetch each ruleset in full.
if ids=$(gh api "repos/$REPO/rulesets" --jq '.[].id'); then
  for id in $ids; do gh api "repos/$REPO/rulesets/$id"; done \
    | jq -s 'map({name, target, enforcement, conditions, bypass_actors, rules}) | sort_by(.name)' > "$OUT/rulesets.json.tmp" \
    && mv "$OUT/rulesets.json.tmp" "$OUT/rulesets.json" && echo "  ok    rulesets.json"
else
  echo "  FAIL  rulesets.json" >&2; FAILED=1
fi
get actions/permissions actions_permissions.json '.[0]'
get actions/permissions/workflow actions_workflow_permissions.json '.[0]'
get actions/secrets actions_secret_names.json '[.[].secrets[].name] | sort'
get actions/variables actions_variable_names.json '[.[].variables[].name] | sort'
get environments environments.json '[.[].environments[]? | {name, protection_rules: [.protection_rules[]? | del(.id, .node_id)], deployment_branch_policy}]'
get labels labels.json '[.[][] | {name, color, description}] | sort_by(.name)'

# ---------------------------------------------------------------- summary
{
  echo "# GitHub export summary"
  echo
  echo "Generated by \`./export-github.sh\` from \`$REPO\`. Do not edit by hand;"
  echo "the reasoning is in [\`github-config.md\`](../github-config.md)."
  echo
  echo "## Rulesets"
  echo
  echo "| Ruleset | Enforcement | Branches | Rules | Bypass actors |"
  echo "|---|---|---|---|---|"
  jq -r '.[] | "| \(.name) | `\(.enforcement)` | \(.conditions.ref_name.include | map("`\(.)`") | join(", ")) | \([.rules[].type] | sort | map("`\(.)`") | join(" · ")) | \(.bypass_actors | length) |"' "$OUT/rulesets.json"
  echo
  echo "## Repository and Actions"
  echo
  echo "| Setting | Value |"
  echo "|---|---|"
  jq -r 'to_entries[] | select(.key != "security_and_analysis") | "| `\(.key)` | `\(.value)` |"' "$OUT/repo.json"
  jq -r '.security_and_analysis | to_entries[] | "| `\(.key)` | `\(.value.status)` |"' "$OUT/repo.json"
  jq -r 'to_entries[] | "| `actions.\(.key)` | `\(.value)` |"' "$OUT/actions_permissions.json" "$OUT/actions_workflow_permissions.json"
  echo "| Actions secrets | $(jq -r 'if length == 0 then "none" else map("`\(.)`") | join(", ") end' "$OUT/actions_secret_names.json") |"
  echo "| Actions variables | $(jq -r 'if length == 0 then "none" else map("`\(.)`") | join(", ") end' "$OUT/actions_variable_names.json") |"
  echo "| Environments | $(jq -r 'if length == 0 then "none" else map("`\(.name)`") | join(", ") end' "$OUT/environments.json") |"
} > "$OUT/SUMMARY.md" && echo "  ok    SUMMARY.md"

echo
echo "Wrote $OUT"
if [[ "$FAILED" -ne 0 ]]; then
  echo "Completed WITH ERRORS - the export is incomplete." >&2
  exit 1
fi
echo "Review with: git diff --stat docs/current-state/github-export/"
